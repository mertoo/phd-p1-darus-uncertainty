"""Generate manuscript tables and figures from structured results only.

    python -m src.analysis.report --rules experiments/configs/v3/analysis_rules.yaml

Every number comes from the bootstrap outputs, metrics.json files or saved
predictions named in the frozen rules file; nothing is typed by hand. The run
fails (no partial output) if any evaluation listed in the eval list, any
bootstrap summary, or any required repeat is missing. An analysis manifest
records the SHA-256 of every input and output.

Outputs in <out_dir>/: tables/*.csv + *.tex, figures/*.pdf, analysis_manifest.json.
"""

import argparse
import csv

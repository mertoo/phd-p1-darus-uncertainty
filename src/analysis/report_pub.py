def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def signed(x, nd):
    """Format x with nd decimals, adding decimals (up to 4) so that a non-zero value never prints as 0 or -0."""
    for d in range(nd, 5):
        t = f"{x:.{d}f}"
        if float(t) != 0.0 or x == 0.0:
            return t
    return f"{x:.2e}"


def ci_signed(est, lo, hi, scale=1.0, nd=2):
    return f"{signed(scale * est, nd)} [{signed(scale * lo, nd)}, {signed(scale * hi, nd)}]"


def ci(est, lo, hi, scale=1.0, nd=3):
    f = f"{{:.{nd}f}}"
    return f"{f.format(scale * est)} [{f.format(scale * lo)}, {f.format(scale * hi)}]"



def tex_table(path, caption, label, colspec, header, rows, note=None, size="\\footnotesize"):
    lines = ["% generated by src.analysis.report_pub from frozen v3 outputs; do not edit by hand",
             "\\begin{table*}[tbp]", "\\centering", size, f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    for r in rows:
        is_rule = r.startswith(("\\midrule", "\\cmidrule", "\\addlinespace"))
        lines.append(r if is_rule else r + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines += [f"\\par\\smallskip\\parbox{{0.95\\textwidth}}{{\\scriptsize {note}}}"]
    lines += ["\\end{table*}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path



        if not ed.windows("test").equals(ref.windows("test")):
            raise ValueError(f"{tag}: windows differ from the reference evaluation")
        iv = ed.interval("test", kind, "horizon_channel", 0.9)
        a = ed.arrays("test")
        t = np.arange(1, a["y"].shape[1] + 1)
        for i, ch in enumerate(CH):
            ax = axes[i, j]
            ax.plot(np.arange(-29, 1), rec[ch].to_numpy()[start:start + 30], color="0.45", lw=1.1, label="history")

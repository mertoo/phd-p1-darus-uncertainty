    fig.legend(h, lbl, loc="lower center", ncol=4, fontsize=11, frameon=False)
    fig.suptitle(f"ID test window {wid} (recording {win.recording.replace('.csv', '')}, start row {start}): "
                 "90% split-conformal intervals", fontsize=12)
    path = f"{out}/fig_example_window.pdf"
    fig.savefig(path)
    plt.close(fig)
    return path, {"window_id": wid, "recording": win.recording, "start_row": start}



def fig_horizon(out):
    fig, axes = plt.subplots(2, 2, figsize=(9, 7.0), sharex=True)
    for j, sp in enumerate(("test", "ood_test")):
        for m, lab, fam, bb in ROWS:
            if fam.endswith("raw") or bb not in ("LSTM", "MLP"):
                continue
            pat, meth = {"AR": (EVAL_TAG.get(m), "conformal"), "EN": (f"{bb.lower()}_ens_rep*", "ensemble"),
                         "DN": (f"{bb.lower()}_mcd_rep*", "mc_dropout"), "GN": (f"{bb.lower()}_gauss_rep*", "gaussian")}[fam]
            cov, wid = [], []
            for p in sorted(glob.glob(f"{METRICS}/{pat}.json")):
                mj = json.load(open(p))
                scale = np.asarray(mj["provenance"]["scale_for_normalised_metrics"])
                v = next(x for x in mj["intervals"] if x["split"] == sp and x["method"] == meth and x["variant"] == "horizon_channel"
                         and abs(x["level"] - 0.9) < 1e-9)
                cov.append(v["coverage_horizon"])
                wid.append((np.asarray(v["width_horizon_channel"]) / scale).mean(1))
            t = np.arange(1, 31)
            axes[0, j].plot(t, np.mean(cov, 0), color=COLOR[fam], ls=LS[bb], lw=1.4, label=f"{lab}, {bb}")
            axes[1, j].plot(t, np.mean(wid, 0), color=COLOR[fam], ls=LS[bb], lw=1.4)
        axes[0, j].axhline(0.9, color="k", ls=":", lw=1)
        axes[0, j].set_title("ID test" if sp == "test" else "OOD test (exploratory)", fontsize=9)
        axes[1, j].set_xlabel("Forecast step (s)")
        for a in axes[:, j]:
            a.grid(alpha=0.3)
    axes[0, 0].set_ylabel("Marginal coverage at nominal 90%")
    axes[1, 0].set_ylabel("Normalised width")
    h, lbl = axes[0, 0].get_legend_handles_labels()
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.legend(h, lbl, fontsize=7.5, loc="lower center", ncol=4, frameon=False)
    p = f"{out}/fig_horizon.pdf"
    fig.savefig(p)
    plt.close(fig)
    return p


